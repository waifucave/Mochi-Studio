// Generates test/fixtures/synthetic-session.json: a SYNTHETIC tracking
// recording (no real camera was used). It scripts a session: neutral pose,
// head turns, a blink, talking, a smile, losing the face, and noise.
// Replace or complement it with real recordings made with the app's
// "Record tracking" button.
import { writeFileSync } from 'node:fs';
import { matrixFromPose } from '../src/core/headPose';
import type { TrackingFrame } from '../src/core/tracking';
import type { TrackingRecording } from '../src/core/recording';

let seed = 42;
const rand = (): number => {
  seed = (seed * 1664525 + 1013904223) >>> 0;
  return seed / 2 ** 32 - 0.5;
};

const frames: TrackingFrame[] = [];
const fps = 30;
for (let i = 0; i < fps * 10; i++) {
  const t = Math.round((i * 1000) / fps);
  const s = i / fps;
  const noise = (a: number): number => rand() * a;
  let yaw = 2 + noise(1.5); // neutral pose is slightly off-centre on purpose
  let pitch = -3 + noise(1.5);
  let roll = 1 + noise(1);
  const bs: Record<string, number> = {
    eyeBlinkLeft: 0.08 + noise(0.04),
    eyeBlinkRight: 0.1 + noise(0.04),
    jawOpen: 0.04 + noise(0.02),
    mouthSmileLeft: 0.02,
    mouthSmileRight: 0.02,
  };
  if (s >= 2 && s < 4) yaw += 25 * Math.sin(((s - 2) / 2) * Math.PI * 2); // turn
  if (s >= 4 && s < 4.2) {
    bs.eyeBlinkLeft = 0.95;
    bs.eyeBlinkRight = 0.95;
  }
  if (s >= 5 && s < 7) bs.jawOpen = 0.3 + 0.3 * Math.abs(Math.sin(s * 9)); // talking
  if (s >= 7 && s < 8) {
    bs.mouthSmileLeft = 0.8;
    bs.mouthSmileRight = 0.75;
    bs.cheekSquintLeft = 0.5;
    bs.cheekSquintRight = 0.5;
  }
  if (s >= 8 && s < 8.5) {
    frames.push({ t, face: false, blendshapes: {} });
    continue;
  }
  if (s >= 8.5) pitch += 15; // looks up after re-acquiring
  roll += 0;
  frames.push({
    t,
    face: true,
    blendshapes: Object.fromEntries(
      Object.entries(bs).map(([k, v]) => [k, Math.min(1, Math.max(0, v))]),
    ),
    matrix: matrixFromPose({ yaw, pitch, roll, z: -40 }).map((x) => Math.round(x * 1e5) / 1e5),
  });
}

const rec: TrackingRecording = {
  format: 'mochi-studio/tracking-recording',
  version: 1,
  source:
    'SYNTHETIC: generated by scripts/make-synthetic-fixture.ts. Neutral 0-2 s (yaw 2, pitch -3, roll 1), turn 2-4 s (±25° yaw), blink 4.0-4.2 s, talking 5-7 s, smile 7-8 s, face lost 8-8.5 s, looking up +15° after 8.5 s.',
  frames,
};
writeFileSync(
  new URL('../test/fixtures/synthetic-session.json', import.meta.url),
  JSON.stringify(rec) + '\n',
);
console.log(`wrote ${frames.length} frames`);
